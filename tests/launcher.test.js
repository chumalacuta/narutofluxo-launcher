test('Offline UUID matches Minecraft Java and accepts only valid nicks', () => {
 assert.equal(createOfflineAccount('Notch').uuid, 'b50ad385-829d-3141-a216-7e7d7539ba7f')
 for (const value of ['ab', 'abc def', 'a@b.com', '../foo', 'x'.repeat(17)]) assert.throws(() => createOfflineAccount(value))
 assert.equal(createOfflineAccount(' Player_123 ').displayName, 'Player_123')
})
test('Migrates offline selection without changing Microsoft authentication', () => {
 const ms = {type:'microsoft', accessToken:'test-token'}
 const r = migrateOfflineAccounts({old:{type:'offline', displayName:'Notch'}, official:ms}, 'old')
 assert.equal(r.selected, createOfflineAccount('Notch').uuid)
 assert.equal(r.accounts.official, ms)
 assert.equal(r.accounts.old, undefined)
})
test('Bundle serves only manifest and referenced objects; defaults never overwrite preferences', async t => {
 const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'fluxo-test-'))
 t.after(() => fs.rm(dir, {recursive:true, force:true}))
 const data = Buffer.from('test-data'), hash = crypto.createHash('sha256').update(data).digest('hex')
 await fs.mkdir(path.join(dir, 'objects'))
 await fs.writeFile(path.join(dir, 'objects', hash), data)
 await fs.writeFile(path.join(dir, 'distribution.json'), JSON.stringify({servers:[{modules:[{artifact:{url:'bundle:'+hash}}]}]}))
 await fs.writeFile(path.join(dir, 'defaults.json'), JSON.stringify([{path:'config/test.cfg', SHA256:hash}]))
 const running = await startBundleServer(dir)
 t.after(() => new Promise(resolve => running.server.close(resolve)))
 const manifest = await (await fetch(running.url)).json()
 const url = manifest.servers[0].modules[0].artifact.url
 assert.equal(await (await fetch(url)).text(), 'test-data')
 assert.equal((await fetch(url, {method:'HEAD'})).headers.get('content-length'), String(data.length))
 assert.equal((await fetch(new URL('/objects/'+hash, url))).status, 404)
 assert.equal((await fetch(url.replace(hash, 'a'.repeat(64)))).status, 404)
 assert.equal((await fetch(url, {method:'POST'})).status, 405)
 for (const p of ['../escape', 'C:/escape', '/escape', 'folder\\escape']) assert.throws(() => safePath(dir,p))
 const instance = path.join(dir, 'instance')
 await seedDefaults(dir, instance)
 const cfg = path.join(instance, 'config/test.cfg')
 await fs.writeFile(cfg, 'user choice')
 await seedDefaults(dir, instance)
 assert.equal(await fs.readFile(cfg, 'utf8'), 'user choice')
 await fs.writeFile(path.join(dir,'objects',hash), 'corrupt')
 await assert.rejects(seedDefaults(dir, instance), /Damaged default/)
})
